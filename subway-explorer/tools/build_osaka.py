START = "梅田"

def dist_km(a, b):
    la = math.radians((a[0] + b[0]) / 2)
    return math.hypot((a[1] - b[1]) * 111.32 * math.cos(la), (a[0] - b[0]) * 110.57)

def load(code):
    d = json.load(open(SRC / f"l{code}.json", encoding="utf-8"))
    return [(s["station_name"], (float(s["lat"]), float(s["lon"]))) for s in d["station_l"]]

def main(check_only):
    errors, pts = [], {}
    lines = []
    for code, lid, name, short, color in LINES:
        st = load(code)
        if lid == "M":   # 미노오카야노 – 센리추오 – 에사카(기타오사카큐코) 직통 + 미도스지선
            kita = load(KITA_OSAKA)
            if kita[-1][0] != st[0][0]:
                errors.append("기타오사카큐코와 미도스지선이 이어지지 않음")
            st = [("箕面萱野", EXTRA["箕面萱野"]), ("箕面船場阪大前", EXTRA["箕面船場阪大前"])] + kita[:-1] + st
        if lid == "C":   # 주오선 유메시마 연장
            if st[0][0] != "コスモスクエア":
                errors.append("주오선 시작역이 코스모스퀘어가 아님")
            st = [("夢洲", EXTRA["夢洲"])] + st
        for n, p in st:
            pts.setdefault(n, []).append(p)
        lines.append({"id": lid, "name": name, "short": short, "color": color, "segs": [[n for n, _ in st]]})

    geo = {}
    for n, ps in pts.items():
        spread = max(dist_km(p, q) for p in ps for q in ps)
        if spread > 1.0:
            errors.append(f"같은 이름인데 1km 넘게 떨어짐: {n} ({spread:.1f}km)")
        geo[n] = (round(sum(p[0] for p in ps) / len(ps), 5), round(sum(p[1] for p in ps) / len(ps), 5))

    for n in geo:
        if n not in LABELS:
            errors.append(f"한국어 표기 없음: {n}")
    for k in list(FACTS) + [START] + [w for a, b, _ in WALKS for w in (a, b)]:
        if k not in geo:
            errors.append(f"노선에 없는 역: {k}")

    hops = []
    for L in lines:
        seq = L["segs"][0]
        for a, b in zip(seq, seq[1:]):
            hops.append((dist_km(geo[a], geo[b]), L["name"], a, b))
    hops.sort(reverse=True)
    print(f"노선 {len(lines)}개, 역 {len(geo)}개")
    print("가장 긴 역 간격 5개:")
    for d, ln, a, b in hops[:5]:
        print(f"  {d:4.1f}km  {ln}  {LABELS.get(a, a)} – {LABELS.get(b, b)}")
    print("가장 짧은 역 간격 3개:")
    for d, ln, a, b in hops[-3:]:
        print(f"  {d:4.1f}km  {ln}  {LABELS.get(a, a)} – {LABELS.get(b, b)}")
    if errors:
        print("오류:\n  " + "\n  ".join(errors)); sys.exit(1)
    if check_only:
        return

    out = {"lines": lines, "geo": geo, "facts": FACTS, "labels": LABELS, "walks": WALKS, "start": START}
    js = "const OSAKA_DATA = " + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";"
    html = HTML.read_text(encoding="utf-8")
    pat = re.compile(r"/\* OSAKA-DATA:BEGIN \*/.*?/\* OSAKA-DATA:END \*/", re.S)
    if not pat.search(html):
        print("index.html에 OSAKA-DATA 표시가 없습니다"); sys.exit(1)
    HTML.write_text(pat.sub(lambda m: "/* OSAKA-DATA:BEGIN */\n" + js + "\n/* OSAKA-DATA:END */", html), encoding="utf-8")
    print(f"index.html 갱신 완료 ({len(js):,}바이트)")

if __name__ == "__main__":
    main("--check" in sys.argv)
